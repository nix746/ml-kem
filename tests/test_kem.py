"""Tests for the full ML-KEM mechanism (FIPS 203, Sections 6 and 7)."""

import pytest
from kyber_py.ml_kem.default_parameters import DEFAULT_PARAMETERS
from kyber_py.ml_kem.ml_kem import ML_KEM

from crypto_primitives import j_hash
from kem import (
    ml_kem_decaps,
    ml_kem_decaps_internal,
    ml_kem_encaps,
    ml_kem_encaps_internal,
    ml_kem_keygen,
    ml_kem_keygen_internal,
)
from params import ML_KEM_512, ML_KEM_768, ML_KEM_1024, MLKEMParams


def _kyber_instance(params: MLKEMParams) -> ML_KEM:
    return ML_KEM(DEFAULT_PARAMETERS[params.name.replace("ML-KEM-", "ML")])


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_roundtrip_and_implicit_rejection(params):
    """Verifies standard roundtrip Decaps(Encaps(ek)) == K and implicit rejection."""
    ek, dk = ml_kem_keygen(params)
    k_enc, c = ml_kem_encaps(params, ek)
    k_dec = ml_kem_decaps(params, dk, c)

    assert len(ek) == params.ek_size
    assert len(dk) == params.dk_size
    assert len(c) == params.ct_size
    assert len(k_enc) == 32
    assert k_dec == k_enc

    # Tampered ciphertext must trigger implicit rejection: K != K_original, K == J(z || c_tampered)
    c_tampered = bytes([c[0] ^ 1]) + c[1:]
    k_rejected = ml_kem_decaps(params, dk, c_tampered)
    assert k_rejected == j_hash(dk[-32:] + c_tampered)
    assert k_rejected != k_enc


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_internal_deterministic_matches_oracle(params):
    """Verifies that internal deterministic functions match kyber-py bit-for-bit."""
    d = bytes(range(32))
    z = bytes(range(32, 64))
    m = bytes(range(64, 96))

    ek, dk = ml_kem_keygen_internal(params, d, z)
    k_shared, c = ml_kem_encaps_internal(params, ek, m)
    k_dec = ml_kem_decaps_internal(params, dk, c)

    oracle = _kyber_instance(params)
    ek_exp, dk_exp = oracle._keygen_internal(d, z)
    k_exp, c_exp = oracle._encaps_internal(ek_exp, m)

    assert ek == ek_exp
    assert dk == dk_exp
    assert c == c_exp
    assert k_shared == k_exp
    assert k_dec == k_exp


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_interop_our_keys_oracle_encaps(params):
    """Interop test: keys generated by our code, encapsulated by kyber-py, decapsulated by us."""
    oracle = _kyber_instance(params)

    ek, dk = ml_kem_keygen(params)
    k_oracle, c = oracle.encaps(ek)
    k_our_dec = ml_kem_decaps(params, dk, c)

    assert k_our_dec == k_oracle


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_interop_oracle_keys_our_encaps(params):
    """Interop test: keys generated by kyber-py, encapsulated by our code, decapsulated by oracle."""
    oracle = _kyber_instance(params)

    ek_oracle, dk_oracle = oracle.keygen()
    k_our_enc, c = ml_kem_encaps(params, ek_oracle)
    k_oracle_dec = oracle.decaps(dk_oracle, c)

    assert k_oracle_dec == k_our_enc


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_interop_tampered_ciphertext_implicit_rejection(params):
    """Interop test: verifying that both implementations yield the exact same rejection key."""
    oracle = _kyber_instance(params)

    ek, dk = ml_kem_keygen(params)
    k_enc, c = ml_kem_encaps(params, ek)

    c_tampered = bytes([c[0] ^ 1]) + c[1:]
    k_our_reject = ml_kem_decaps(params, dk, c_tampered)
    k_oracle_reject = oracle.decaps(dk, c_tampered)

    assert k_our_reject == k_oracle_reject
    assert k_our_reject != k_enc


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_encaps_validation(params):
    """Validates type and modulus checks in ml_kem_encaps (FIPS 203, Section 7.2)."""
    ek, _ = ml_kem_keygen(params)

    # Check 1: Wrong length
    with pytest.raises(ValueError, match="Invalid encapsulation key length"):
        ml_kem_encaps(params, ek[:-1])
    with pytest.raises(ValueError, match="Invalid encapsulation key length"):
        ml_kem_encaps(params, ek + b"\x00")

    # Check 2: Modulus check (non-canonical coefficient >= 3329)
    bad_ek = bytes([0xFF, 0x0F]) + ek[2:]
    with pytest.raises(ValueError, match="Encapsulation key modulus check failed"):
        ml_kem_encaps(params, bad_ek)


@pytest.mark.parametrize("params", [ML_KEM_512, ML_KEM_768, ML_KEM_1024])
def test_ml_kem_decaps_validation(params):
    """Validates type and hash checks in ml_kem_decaps (FIPS 203, Section 7.3)."""
    ek, dk = ml_kem_keygen(params)
    _, c = ml_kem_encaps(params, ek)

    # Check 1: Ciphertext length check
    with pytest.raises(ValueError, match="Invalid ciphertext length"):
        ml_kem_decaps(params, dk, c[:-1])
    with pytest.raises(ValueError, match="Invalid ciphertext length"):
        ml_kem_decaps(params, dk, c + b"\x00")

    # Check 2: Decapsulation key length check
    with pytest.raises(ValueError, match="Invalid decapsulation key length"):
        ml_kem_decaps(params, dk[:-1], c)
    with pytest.raises(ValueError, match="Invalid decapsulation key length"):
        ml_kem_decaps(params, dk + b"\x00", c)

    # Check 3: Hash check
    k = params.k
    h_start = 768 * k + 32
    corrupted_dk = dk[:h_start] + bytes([dk[h_start] ^ 1]) + dk[h_start + 1 :]
    with pytest.raises(ValueError, match="Decapsulation key hash check failed"):
        ml_kem_decaps(params, corrupted_dk, c)
